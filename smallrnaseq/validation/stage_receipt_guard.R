args <- commandArgs(trailingOnly=TRUE)
source_root <- normalizePath(args[[1]],mustWork=TRUE)
project_root <- normalizePath(args[[2]],mustWork=TRUE)
exprs <- parse(file.path(source_root,"shared/R/runtime.R"))
expr <- Filter(function(x)is.call(x)&&identical(x[[1]],as.name("<-"))&&identical(x[[2]],as.name("validate_stage_artifact")),as.list(exprs))
stopifnot(length(expr)==1L)
env <- new.env(parent=globalenv())
env$read_tsv_flex <- function(path)read.delim(path,check.names=FALSE,stringsAsFactors=FALSE)
eval(expr[[1]],envir=env)
artifact <- file.path(project_root,"result/differential/7_mirna/tables/06_de/de_miRNA_results.csv")
env$ROOT_DIR <- project_root
current <- env$validate_stage_artifact(artifact,"differential","mirna")
stopifnot(current$valid)
testroot <- tempfile("smallrna-stage-guard-")
receipt_root <- file.path(testroot,"result/differential")
dir.create(receipt_root,recursive=TRUE)
files <- c("run_status.tsv","module_status.tsv","input_signature.tsv")
file.copy(file.path(project_root,"result/differential",files),file.path(receipt_root,files))
env$ROOT_DIR <- testroot
runfile <- file.path(receipt_root,"run_status.tsv")
status <- env$read_tsv_flex(runfile)
status$State <- "failed"
write.table(status,runfile,sep="\t",quote=FALSE,row.names=FALSE)
failed <- env$validate_stage_artifact(artifact,"differential","mirna")
stopifnot(!failed$valid,grepl("not_run",failed$reason))
file.copy(file.path(project_root,"result/differential/run_status.tsv"),runfile,overwrite=TRUE)
sigfile <- file.path(receipt_root,"input_signature.tsv")
sig <- env$read_tsv_flex(sigfile)
sig$MD5[[1]] <- strrep("0",32)
write.table(sig,sigfile,sep="\t",quote=FALSE,row.names=FALSE)
stale <- env$validate_stage_artifact(artifact,"differential","mirna")
stopifnot(!stale$valid,grepl("STALE_OUTPUTS",stale$reason))
sig$Path[[1]] <- file.path(testroot,"missing_input")
write.table(sig,sigfile,sep="\t",quote=FALSE,row.names=FALSE)
missing <- env$validate_stage_artifact(artifact,"differential","mirna")
stopifnot(!missing$valid,grepl("STALE_OUTPUTS",missing$reason))
cat("current receipt PASS; failed receipt blocked; changed MD5 blocked; missing input blocked\n")
